"""Which request fixture goes to which route, and what response is expected.

`tests/fixtures/manifest.json` maps a fixture to a schema name -- it does not
say which route sends or receives it (T-178 was deliberately silent on that;
see `docs/contracts/dependent-notes.md`). This module is the one place that
makes that pairing explicit, by hand, once, so both the fixture-replay stub
and the live-server harness agree on it.

Four response schemas (`Ticket`, `Agent`, `Review`, `Member`, `Channel`) have
no dedicated fixture -- they only appear nested inside a screen fixture. Those
cases use `FixtureRef.extract` instead of inventing new example JSON.

PROJECT_ID and the other sample ids below are drawn from the fixtures
themselves (e.g. `tests/fixtures/tickets/detail-claimed.json` uses
`DEMO-13` / `prj_demo0001`) purely so a human reading a request log sees
consistent ids; the stub does not check referential integrity between them.
"""

from __future__ import annotations

from dataclasses import dataclass, field

from .fixtures import FixtureRef

PROJECT_ID = "prj_demo0001"
TICKET_ID = "DEMO-13"
AGENT_ID = "agt_backend01"
