RUN_ID = "run_00000005"
REVIEW_ID = "rev_00000002"
RUNNER_ID = "rnr_00000001"


@dataclass(frozen=True)
class Case:
    operation_id: str
    variant: str  # distinguishes multiple fixtures against the same route
    request: FixtureRef | None
    response: FixtureRef
    path_values: dict = field(default_factory=dict)
    query_values: dict = field(default_factory=dict)

    @property
    def label(self) -> str:
        return self.operation_id if self.variant == "default" else f"{self.operation_id}[{self.variant}]"


def _ref(rel_path: str, *extract: object) -> FixtureRef:
    return FixtureRef(rel_path, tuple(extract))


